import assert from "node:assert/strict";
import { spawnSync, execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import test from "node:test";

// Release scripts run on the server after `git pull`. They must read the same env files as the
// app (Next.js precedence: .env.production.local, .env.local, .env.production, .env), not only .env.local.
function serverFolder(files) {
  const dir = mkdtempSync(path.join(tmpdir(), "ppa-release-"));
  for (const [name, content] of Object.entries(files)) {
    mkdirSync(path.dirname(path.join(dir, name)), { recursive: true });
    if (content === null) copyFileSync(name, path.join(dir, name));
    else writeFileSync(path.join(dir, name), content);
  }
  return dir;
}
const runScript = (script, cwd, env = {}) => spawnSync(process.execPath, [path.resolve(script)], { cwd, encoding: "utf8", env: { PATH: process.env.PATH, ...env }, timeout: 30_000 });

test("the rich menu script reads the LIFF ID from the server's .env.production.local", () => {
  const dir = serverFolder({
    "config/line-rich-menu-main.json": null,
    "public/line/rich-menu-main.png": "png",
    ".env.production.local": "NEXT_PUBLIC_LINE_LIFF_ID=2000000000-TESTLIFF\n",
  });
  const result = runScript("scripts/create-line-rich-menu.mjs", dir, { LINE_RICH_MENU_DRY_RUN: "true" });
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /https:\/\/liff\.line\.me\/2000000000-TESTLIFF\?screen=plans/);
});

test("db:init reads the database settings from the server's .env.production.local", () => {
  // Port 1 on localhost refuses at once: the script gets past its settings check and tries to connect.
  const dir = serverFolder({
    "database/schema.sql": "SELECT 1;\n",
    ".env.production.local": "DB_HOST=127.0.0.1\nDB_PORT=1\nDB_USER=release_test\nDB_NAME=release_test\n",
  });
  const result = runScript("scripts/db-init.mjs", dir);
  assert.notEqual(result.status, 0);
  assert.doesNotMatch(result.stderr, /Missing DB_/, "settings were found");
  assert.match(result.stderr, /ECONNREFUSED/);
});

test("files the build regenerates stay out of git, so a server pull never conflicts with its own build", () => {
  const ignored = readFileSync(".gitignore", "utf8").split(/\r?\n/);
  assert.ok(ignored.includes("next-env.d.ts"), "next-env.d.ts is generated by Next.js");
  assert.ok(ignored.includes("*.tsbuildinfo"), "tsconfig.tsbuildinfo is written by every type check");
  assert.equal(execFileSync("git", ["ls-files", "next-env.d.ts", "tsconfig.tsbuildinfo"], { encoding: "utf8" }).trim(), "");
});
